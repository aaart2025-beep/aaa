/** Return a product with Hebrew copy swapped in when the language is Hebrew
 * and a translation exists; otherwise the product unchanged. The English name
 * is always preserved. */
export function localizeProduct(p: Product, lang: Lang): Product {
  if (lang !== "he") return p;
  const he = PRODUCT_HE[p.slug];
  if (!he) return p;
  return {
    ...p,
    tagline: he.tagline ?? p.tagline,
    description: he.description ?? p.description,
    details: he.details ?? p.details,
    colors: he.colors ?? p.colors,
  };
}
